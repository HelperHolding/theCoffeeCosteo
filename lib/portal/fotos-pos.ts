export const rutaFotoPos = (codigo: string) => `/productos/pos/${codigo}.webp`;

/** Foto de una receta a partir de sus códigos del POS: la del primer código (en orden) que tenga foto. */
export function fotoDeCodigos(codigos: readonly string[]): { codigo: string; src: string } | null {
  const codigo = [...codigos].sort().find((c) => FOTOS_POS.has(c));
  return codigo ? { codigo, src: rutaFotoPos(codigo) } : null;
}
